CREATE OR REPLACE VIEW v_user_recent_wins AS
  SELECT user_email,
         SUM(montant_eur) AS total_won_7d,
         COUNT(*)         AS nb_wins_7d
    FROM transactions
   WHERE type = 'win'
     AND date > NOW() - INTERVAL '7 days'
   GROUP BY user_email;

